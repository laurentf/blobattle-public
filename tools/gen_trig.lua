local ANGLES = 1024
local QUARTER = ANGLES / 4
local SCALE = 16384

local function round(v)
  if v >= 0 then
    return math.floor(v + 0.5)
  end
  return -math.floor(-v + 0.5)
end

local quarter = {}
for i = 0, QUARTER do
  quarter[i] = round(math.sin(2 * math.pi * i / ANGLES) * SCALE)
end

local values = {}
for i = 0, ANGLES - 1 do
  local q, r = math.floor(i / QUARTER), i % QUARTER
  local v
  if q == 0 then
    v = quarter[r]
  elseif q == 1 then
    v = quarter[QUARTER - r]
  elseif q == 2 then
    v = 0 - quarter[r]
  else
    v = 0 - quarter[QUARTER - r]
  end
  values[#values + 1] = v
end

local lines = {
  "-- Generated by tools/gen_trig.lua. Do not edit: run `make trig`.",
  'local fixed = require("shared.sim.fixed")',
  "",
  "local M = {}",
  "",
  "M.ANGLES = " .. ANGLES,
  "M.SCALE = " .. SCALE,
  "",
  "local SIN = {",
}
for _, v in ipairs(values) do
  lines[#lines + 1] = "  " .. v .. ","
end
lines[#lines + 1] = "}"
lines[#lines + 1] = ""
lines[#lines + 1] = "function M.sin(angle)"
lines[#lines + 1] = "  return SIN[fixed.mod(angle, " .. ANGLES .. ") + 1]"
lines[#lines + 1] = "end"
lines[#lines + 1] = ""
lines[#lines + 1] = "function M.cos(angle)"
lines[#lines + 1] = "  return SIN[fixed.mod(angle + " .. QUARTER .. ", " .. ANGLES .. ") + 1]"
lines[#lines + 1] = "end"
lines[#lines + 1] = ""
lines[#lines + 1] = "return M"

local out = assert(io.open(arg[1] or "shared/sim/trig.lua", "wb"))
out:write(table.concat(lines, "\n"), "\n")
out:close()
