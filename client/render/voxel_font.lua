  Z = { "#####", "....#", "...#.", "..#..", ".#...", "#....", "#####" },
}

local glyphs = {}

for char, rows in pairs(ROWS) do
  local cells = {}
  for r, row in ipairs(rows) do
    for x = 1, #row do
      if row:sub(x, x) == "#" then
        cells[#cells + 1] = { x = x - 1, y = M.HEIGHT - r }
      end
    end
  end
  glyphs[char] = cells
end

function M.glyph(char)
  local cells = glyphs[char]
  if cells == nil then
    return nil, "no_glyph"
  end
  return cells
end

function M.layout(text)
  local letters, x = {}, 0
  for char in text:gmatch(".") do
    if char ~= " " then
      letters[#letters + 1] = { char = char, cells = assert(M.glyph(char)), x = x }
    end
    x = x + M.WIDTH + M.SPACING
  end
  return { letters = letters, width = math.max(0, x - M.SPACING) }
end

return M
