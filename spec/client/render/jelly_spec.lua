local jelly = require("render.jelly")

local DT = 1 / 60

local function run(j, seconds, motion)
  local lowest, highest = math.huge, -math.huge
  for _ = 1, math.floor(seconds / DT) do
    jelly.step(j, DT, motion or jelly.REST)
    local shape = jelly.shape(j)
    lowest, highest = math.min(lowest, shape.sy), math.max(highest, shape.sy)
  end
  return lowest, highest
end

describe("🫧 the jelly spring of a blob (§7.4)", function()
  it("🫧 squashes on landing, then settles back to its height", function()
    local j = jelly.new(1)
    run(j, 1)
    jelly.event(j, { type = "landed" })
    local lowest = run(j, 0.3)
    assert.is_true(lowest < 0.9, "lowest height " .. lowest)
    run(j, 2)
    local shape = jelly.shape(j)
    assert.is_true(math.abs(shape.sy - 1) < 0.05, "settled at " .. shape.sy)
    assert.is_true(math.abs(shape.sx * shape.sx * shape.sy - 1) < 0.01, "keeps its volume")
  end)

  it("🫧 squashes on a rebound as on a landing", function()
    local j = jelly.new(1)
    run(j, 1)
    jelly.event(j, { type = "rebounded" })
    local lowest = run(j, 0.3)
    assert.is_true(lowest < 0.9, "lowest height " .. lowest)
  end)

  it("🫧 stretches while it rises and leans while it walks", function()
    local j = jelly.new(1)
    local _, highest = run(j, 0.4, { vx = 0, vy = -2.4, walk = 0 })
    assert.is_true(highest > 1.1, "highest " .. highest)
    local w = jelly.new(1)
    run(w, 0.5, { vx = 0, vy = 0, walk = 1 })
    assert.is_true(jelly.shape(w).lean < -0.05, "lean " .. jelly.shape(w).lean)
  end)

  it("🥊 stretches up on an uppercut, well above a shot", function()
    local shot, punch = jelly.new(1), jelly.new(1)
    run(shot, 1)
    run(punch, 1)
    jelly.event(shot, { type = "fired", weapon = "bazooka" })
    jelly.event(punch, { type = "fired", weapon = "uppercut" })
    local _, low = run(shot, 0.3)
    local _, high = run(punch, 0.3)
    assert.is_true(high > 1.3, "highest " .. high)
    assert.is_true(high > low + 0.15, high .. " against " .. low)
    local hop = jelly.new(1)
    run(hop, 1)
    jelly.event(hop, { type = "fired" })
    local _, hopped = run(hop, 0.3)
    assert.are.equal(low, hopped)
  end)

  it("🫧 trembles when hurt, more for a bigger hit, and calms down", function()
    local small, big = jelly.new(1), jelly.new(1)
    jelly.event(small, { type = "damaged", amount = 5 })
    jelly.event(big, { type = "damaged", amount = 50 })
    assert.is_true(jelly.shape(big).wobble > jelly.shape(small).wobble)
    run(big, 3)
    assert.is_true(jelly.shape(big).wobble < 0.01)
  end)

  it("🫧 becomes a flat grey puddle when it dies, and stays one", function()
    local j = jelly.new(1)
    jelly.event(j, { type = "died", cause = "hp" })
    run(j, 1)
    local shape = jelly.shape(j)
    assert.is_true(shape.dead)
    assert.is_true(shape.sy < 0.3 and shape.sx > 1.2)
    jelly.event(j, { type = "landed" })
    run(j, 1)
    assert.are.same(shape, jelly.shape(j))
  end)
end)
